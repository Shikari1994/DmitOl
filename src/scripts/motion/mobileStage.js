/* ─── Мобильный клиент: ряд аппаратов выходит снизу ───
   Суть приёма — РАЗНАЯ скорость у среднего и боковых: одна на всех дала
   бы картинку, которая просто едет, разная — сцену, которая собирается
   по мере подхода.

   Окно — подход секции к экрану: к моменту, когда ряд прочитан целиком,
   движение закончено, дальше он стоит.

   scrub с задержкой, а не жёсткий: единственное место на странице, где
   инерция уместна — предметы тяжёлые и должны догонять скролл. */
import { gsap } from 'gsap'
import { reduce } from './env.js'

if (!reduce) {
  const stage = document.querySelector('[data-mob-stage]')
  const phones = stage ? gsap.utils.toArray('[data-mob-phone]', stage) : []

  phones.forEach((el, i) => {
    // 0 — средний (ближний план, короткий ход), 1 — боковые
    const depth = Number(el.dataset.depth) || 0

    /* Боковые стартуют ниже и мельче и по ходу скролла выходят на свой
       размер; средний почти на месте с начала — он ось, вокруг которой
       идёт сборка. Строго по вертикали, без бокового сноса и наклона. */
    gsap.fromTo(
      el,
      {
        yPercent: 8 + depth * 26,
        scale: 1 - depth * 0.07,
      },
      {
        yPercent: 0,
        scale: 1,
        transformOrigin: '50% 100%',
        /* Средний приходит раньше боковых и притормаживает у места, боковые
           дособираются линейно — отсюда ощущение, что ряд живой, а не едет
           одним куском. */
        ease: depth === 0 ? 'power2.out' : 'none',
        scrollTrigger: {
          trigger: stage,
          start: 'top bottom',
          end: 'bottom bottom',
          /* разный scrub — разная инерция: боковые тяжелее и заметнее
             догоняют колесо, средний держится ближе к скроллу */
          scrub: depth === 0 ? 0.45 : 1,
          invalidateOnRefresh: true,
        },
      },
    )

    /* Второй такт: когда секция уходит вверх, средний чуть отстаёт от
       скролла, боковые чуть обгоняют. Расхождение мелкое, но сцена
       продолжает дышать, а не превращается в статичный кадр.

       Цель — картинка ВНУТРИ figure, а не сама figure: два scrub-твина на
       одном yPercent спорили бы на стыке окон (у каждого своя задержка).
       Так сборка живёт на обёртке, дрейф — на вложенном узле. */
    gsap.to(el.querySelector('img'), {
      yPercent: depth === 0 ? 4 : -5,
      ease: 'none',
      scrollTrigger: {
        trigger: stage,
        start: 'bottom bottom',
        end: 'bottom top',
        scrub: depth === 0 ? 0.45 : 1,
        invalidateOnRefresh: true,
      },
    })
  })
}
